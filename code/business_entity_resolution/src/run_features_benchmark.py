"""
ML Challenge 2026: Business Entity Resolution
Module: run_features_benchmark.py

Benchmarks pairwise feature extraction on candidate pairs generated by Configuration H:
1. Loads 1,000 validation S1 entities and target pool.
2. Generates ~55,000 candidate pairs with blocking evidence using Configuration H.
3. Extracts dense 96-dimensional float32 feature matrix.
4. Validates zero NaN/inf, data types, memory overhead, and throughput (pairs/sec).
5. Outputs detailed summary and 5-10 diverse example feature vectors.
"""

import os
import sys
import time
import csv
import tracemalloc
from typing import Dict, List, Set, Tuple, Any
import numpy as np

sys.stdout.reconfigure(encoding='utf-8', errors='backslashreplace')

# Add src to path
sys.path.insert(0, os.path.dirname(__file__))

from preprocessing import (
    normalize_name,
    compact_string,
    remove_legal_suffix,
    transliterate_name,
    normalize_address,
    extract_postal_code,
    extract_house_number,
    has_indic_characters
)
from blocking import create_config_h_generator
from features import (
    PairwiseFeatureExtractor,
    enrich_record_for_features,
    FEATURE_NAMES,
    NUM_FEATURES
)

BASE_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))


def run_benchmark():
    print("=" * 80)
    print("BENCHMARKING PAIRWISE FEATURE ENGINEERING (CONFIGURATION H)")
    print("=" * 80)

    tracemalloc.start()
    t_start = time.time()

    # 1. Ingest 1,000 validation S1 records (600 US, 400 India)
    print("\n[1/5] Ingesting Stratified Validation Cohort (1,000 S1 records)...")
    s1_cohort: Dict[str, Dict[str, Any]] = {}
    us_count, ind_count = 0, 0
    us_limit, ind_limit = 600, 400

    s1_path = os.path.join(BASE_DIR, "dataset", "train", "train_source1.tsv")
    with open(s1_path, "r", encoding="utf-8") as f:
        r = csv.reader(f, delimiter="\t")
        next(r)
        for row in r:
            eid, name, addr, country = row[0], row[1], row[2], row[3]
            if country == "US" and us_count < us_limit:
                s1_cohort[eid] = enrich_record_for_features({
                    "entity_id": eid, "name": name, "address": addr, "country": country
                })
                us_count += 1
            elif country == "India" and ind_count < ind_limit:
                s1_cohort[eid] = enrich_record_for_features({
                    "entity_id": eid, "name": name, "address": addr, "country": country
                })
                ind_count += 1
            if us_count >= us_limit and ind_count >= ind_limit:
                break

    # 2. Ingest Ground Truth for Validation Cohort
    print("[2/5] Loading Ground Truth labels...")
    ground_truth: Dict[str, Set[str]] = {}
    gt_targets = set()
    gt_path = os.path.join(BASE_DIR, "dataset", "train", "train_ground_truth.tsv")
    with open(gt_path, "r", encoding="utf-8") as f:
        r = csv.reader(f, delimiter="\t")
        next(r)
        for row in r:
            s1_id = row[0]
            if s1_id in s1_cohort:
                matches = set(x.strip() for x in row[1].split(",") if x.strip())
                ground_truth[s1_id] = matches
                gt_targets.update(matches)

    print(f"  Ground truth true links in cohort: {sum(len(m) for m in ground_truth.values()):,}")

    # 3. Ingest Target Pool (True matches + 100,000 distractors)
    print("\n[3/5] Ingesting Target Pool (True matches + 100,000 distractors)...")
    target_records: Dict[str, Dict[str, Any]] = {}
    needed_s2 = {eid for eid in gt_targets if eid.startswith("S2-")}
    needed_s3 = {eid for eid in gt_targets if eid.startswith("S3-")}

    for fname, needed_set, distractor_limit in [
        ("train_source2.tsv", needed_s2, 50000),
        ("train_source3.tsv", needed_s3, 50000)
    ]:
        fpath = os.path.join(BASE_DIR, "dataset", "train", fname)
        with open(fpath, "r", encoding="utf-8") as f:
            r = csv.reader(f, delimiter="\t")
            next(r)
            d_count = 0
            for row in r:
                eid, name, addr, country = row[0], row[1], row[2], row[3]
                if eid in needed_set or d_count < distractor_limit:
                    target_records[eid] = enrich_record_for_features({
                        "entity_id": eid, "name": name, "address": addr, "country": country
                    })
                    if eid not in needed_set:
                        d_count += 1

    print(f"  Target pool size: {len(target_records):,} records")

    # 4. Generate Candidates under Configuration H with Blocking Evidence
    print("\n[4/5] Executing Configuration H Candidate Generation with Rule Evidence...")
    blocker = create_config_h_generator(ngram_top_k=10, ngram_min_sim=0.25)
    t_block_start = time.time()
    blocker.fit_target_records(list(target_records.values()))
    s1_list = list(s1_cohort.values())
    evidence_map = blocker.generate_candidates_with_evidence(s1_list)
    t_block_end = time.time()

    # Flatten candidate pairs
    candidate_pairs: List[Tuple[str, str, Set[str]]] = []
    for s1_id, cand_dict in evidence_map.items():
        for cand_id, rule_set in cand_dict.items():
            if cand_id in target_records:
                candidate_pairs.append((s1_id, cand_id, rule_set))

    total_pairs = len(candidate_pairs)
    print(f"  Generated {total_pairs:,} candidate pairs across {len(s1_cohort)} S1 entities.")
    print(f"  Average candidates / S1: {total_pairs / len(s1_cohort):.2f}")
    print(f"  Blocking execution time: {t_block_end - t_block_start:.2f}s")

    # 5. Extract Feature Matrix
    print(f"\n[5/5] Extracting 96-Dimensional Feature Matrix for {total_pairs:,} Pairs...")
    extractor = PairwiseFeatureExtractor()
    t_feat_start = time.time()
    feature_matrix = extractor.extract_batch_vectors(
        s1_cohort, target_records, candidate_pairs, chunk_size=10000
    )
    t_feat_end = time.time()

    feat_duration = t_feat_end - t_feat_start
    throughput = total_pairs / feat_duration if feat_duration > 0 else 0.0

    current_mem, peak_mem = tracemalloc.get_traced_memory()
    tracemalloc.stop()

    # 6. Quality Checks & Verification
    nan_count = int(np.isnan(feature_matrix).sum())
    inf_count = int(np.isinf(feature_matrix).sum())
    matrix_bytes = feature_matrix.nbytes
    matrix_mb = matrix_bytes / (1024 * 1024)

    print("\n" + "=" * 80)
    print("FEATURE EXTRACTION BENCHMARK RESULTS")
    print("=" * 80)
    print(f"1. Total Candidate Pairs Processed : {total_pairs:,}")
    print(f"2. Number of Generated Features   : {NUM_FEATURES}")
    print(f"3. Feature Matrix Shape            : {feature_matrix.shape}")
    print(f"4. Matrix Data Type                : {feature_matrix.dtype}")
    print(f"5. NaN Value Count                 : {nan_count}")
    print(f"6. Infinity Value Count            : {inf_count}")
    print(f"7. Feature Matrix Memory Size      : {matrix_mb:.2f} MB")
    print(f"8. Peak Python Heap Memory         : {peak_mem / (1024 * 1024):.2f} MB")
    print(f"9. Feature Extraction Runtime      : {feat_duration:.2f} seconds")
    print(f"10. Feature Extraction Throughput  : {throughput:,.1f} pairs/second")

    # 7. Complete Feature Registry and Summary Stats
    print("\n--- Complete Feature Registry (96 Features) ---")
    print(f"{'Idx':<4} | {'Feature Name':<38} | {'Mean':<8} | {'Min':<6} | {'Max':<6} | {'NonZero%':<8}")
    print("-" * 80)
    for idx, fname in enumerate(FEATURE_NAMES):
        col = feature_matrix[:, idx]
        mean_val = float(np.mean(col))
        min_val = float(np.min(col))
        max_val = float(np.max(col))
        nonzero_pct = float(np.count_nonzero(col) / len(col) * 100)
        print(f"{idx:<4} | {fname:<38} | {mean_val:<8.4f} | {min_val:<6.2f} | {max_val:<6.2f} | {nonzero_pct:<7.2f}%")

    # 8. Extract 8 Representative Concrete Feature Vectors
    print("\n--- 8 Representative Example Feature Vectors ---")
    # Identify diverse cases:
    # 1: Exact True Match
    # 2: Legal Suffix Variation True Match
    # 3: Typo / Fuzzy True Match
    # 4: Cross-Script Latin -> Indic True Match
    # 5: Missing Address True Match
    # 6: Same Postal / Same House True Match
    # 7: Same Name but Different Address (Homonym/Franchise Distractor)
    # 8: Address-only Distractor

    selected_indices = []
    labels = []

    for i, (s1_id, cand_id, rules) in enumerate(candidate_pairs):
        is_true = cand_id in ground_truth.get(s1_id, set())
        row = feature_matrix[i]
        name_exact = row[FEATURE_NAMES.index("name_exact")]
        name_nosuff = row[FEATURE_NAMES.index("name_nosuff_exact")]
        is_cross = row[FEATURE_NAMES.index("is_cross_script")]
        s1_addr_miss = row[FEATURE_NAMES.index("s1_address_missing")]
        cand_addr_miss = row[FEATURE_NAMES.index("candidate_address_missing")]
        name_lev = row[FEATURE_NAMES.index("name_normalized_levenshtein")]
        addr_lev = row[FEATURE_NAMES.index("address_normalized_levenshtein")]

        if is_true and name_exact == 1.0 and addr_lev > 0.8 and "exact_true" not in labels:
            selected_indices.append((i, "Example 1: Exact Name & Address Match (True Match)", is_true))
            labels.append("exact_true")
        elif is_true and name_nosuff == 1.0 and name_exact == 0.0 and "nosuff_true" not in labels:
            selected_indices.append((i, "Example 2: Legal Suffix Variation (True Match)", is_true))
            labels.append("nosuff_true")
        elif is_true and 0.70 <= name_lev < 0.95 and name_exact == 0.0 and "fuzzy_true" not in labels:
            selected_indices.append((i, "Example 3: Typo / Fuzzy Name Variation (True Match)", is_true))
            labels.append("fuzzy_true")
        elif is_true and is_cross == 1.0 and "cross_true" not in labels:
            selected_indices.append((i, "Example 4: Latin -> Indic Cross-Script (True Match)", is_true))
            labels.append("cross_true")
        elif is_true and (s1_addr_miss == 1.0 or cand_addr_miss == 1.0) and "miss_addr_true" not in labels:
            selected_indices.append((i, "Example 5: Missing Address Record (True Match)", is_true))
            labels.append("miss_addr_true")
        elif not is_true and name_exact == 1.0 and addr_lev < 0.20 and (s1_addr_miss + cand_addr_miss == 0) and "homonym_false" not in labels:
            selected_indices.append((i, "Example 6: Homonym / Same Name Different City (Distractor / False)", is_true))
            labels.append("homonym_false")
        elif not is_true and name_lev < 0.40 and addr_lev > 0.60 and "addr_distractor" not in labels:
            selected_indices.append((i, "Example 7: Same Address / Building, Different Business (Distractor / False)", is_true))
            labels.append("addr_distractor")
        elif not is_true and name_lev < 0.35 and addr_lev < 0.30 and "random_cand" not in labels:
            selected_indices.append((i, "Example 8: Weak Candidate / Single N-Gram Overlap (Distractor / False)", is_true))
            labels.append("random_cand")

        if len(selected_indices) >= 8:
            break

    # If any specific category wasn't found in early iterations, fill up to 8
    curr_idx = 0
    while len(selected_indices) < 8 and curr_idx < total_pairs:
        if curr_idx not in [x[0] for x in selected_indices]:
            s1_id, cand_id, _ = candidate_pairs[curr_idx]
            is_true = cand_id in ground_truth.get(s1_id, set())
            selected_indices.append((curr_idx, f"Example {len(selected_indices)+1}: Candidate Pair ({'True Match' if is_true else 'Distractor'})", is_true))
        curr_idx += 100

    key_feature_subset = [
        "name_exact", "name_nosuff_exact", "name_translit_exact", "name_normalized_levenshtein",
        "name_token_sort_ratio", "name_char3_jaccard", "consonant_skeleton_exact",
        "address_exact", "address_normalized_levenshtein", "address_token_jaccard",
        "house_number_exact", "postal_code_exact", "s1_address_missing", "candidate_address_missing",
        "is_cross_script", "candidate_source_is_S2", "candidate_source_is_S3",
        "blocked_exact_name", "blocked_postal", "blocked_consonant_skeleton", "num_blocking_rules"
    ]

    for pair_idx, desc, is_true in selected_indices:
        s1_id, cand_id, rules = candidate_pairs[pair_idx]
        s1 = s1_cohort[s1_id]
        cand = target_records[cand_id]
        vec = feature_matrix[pair_idx]

        print(f"\n--- {desc} ---")
        print(f"  S1: [{s1_id}] '{s1['name']}' | Addr: '{s1['address'][:50]}...' | Country: {s1['country']}")
        print(f"  Tgt: [{cand_id}] '{cand['name']}' | Addr: '{cand['address'][:50]}...' | Country: {cand['country']}")
        if cand["has_indic"]:
            print(f"  Transliterated Tgt: '{cand['translit_name']}'")
        print(f"  Ground Truth Link: {'TRUE MATCH (Positive)' if is_true else 'NON-MATCH (Negative)'}")
        print(f"  Generating Rules : {sorted(rules)}")
        print("  Key Feature Values:")
        for kfeat in key_feature_subset:
            kidx = FEATURE_NAMES.index(kfeat)
            print(f"    {kfeat:<32}: {vec[kidx]:.4f}")


if __name__ == "__main__":
    run_benchmark()
