"""
ML Challenge 2026: Business Entity Resolution
Module: train_data.py

Constructs labeled pairwise machine learning training and validation datasets
from candidate pairs generated by Configuration H blocking:

1. Entity-Level Train/Validation Splitting:
   - 80% Source 1 entities for Training, 20% for Validation (seed=42).
   - Strict entity isolation: zero S1 overlap between splits.
   - Validation retains ALL candidate pairs for unbiased macro F0.5 evaluation.

2. Pairwise Ground-Truth Labeling:
   - Label 1 = True Match (candidate ID in train_ground_truth.tsv for that S1).
   - Label 0 = Non-Match (candidate produced by blocking, but not in ground truth).
   - Strictly uses hard negatives produced by Configuration H (no random Cartesian pairs).

3. Controlled Hard-Negative Sampling & Entity Balancing:
   - 100% of blocking-recalled positive candidate pairs are retained.
   - Negatives prioritized by composite hardness score:
     * High name / transliterated name similarity
     * Multi-rule blocking agreement (e.g. consonant skeleton + postal + address token)
     * Commercial homonyms (exact name, different address)
     * Same postal code or house number
   - Entity balancing: prevents outlier S1 entities from dominating the pairwise loss.
   - Benchmarks multiple negative:positive ratios (1:1, 2:1, 4:1, and unconstrained).

4. High-Performance Feature Matrix Construction:
   - Computes 96 dense float32 features via features.py in chunked streaming batches.
   - Verifies zero NaN and zero infinity values.
   - Saves compressed NPZ archives: dataset/processed/train_data.npz and val_data.npz.

5. Rigorous Ground-Truth Integrity Checks:
   - Every positive pair confirmed in ground truth.
   - Zero negative pairs in ground truth.
   - Zero S1 leakage across splits.
   - All target records confirmed as S2 or S3 (zero S1-S1 pairs).
"""

