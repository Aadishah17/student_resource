# 2. Hard-Negative Scoring & Prioritization
# ==============================================================================

def compute_negative_hardness(
    s1_rec: Dict[str, Any],
    cand_rec: Dict[str, Any],
    rule_set: Set[str]
) -> float:
    """
    Computes a composite hardness score for a negative candidate pair.
    Higher score indicates a challenging distractor (e.g. homonym, same street/colony,
    multi-rule blocking agreement) that provides high gradient signal for ML training.
    """
    score = 0.0

    # 1. Multi-rule agreement (strongest indicator of challenging distractor)
    score += len(rule_set) * 2.0

    # 2. Specific high-precision rule triggers
    if "blocked_exact_name" in rule_set:
        score += 8.0  # Commercial homonym / franchise (same name, different location)
    if "blocked_compact_name" in rule_set or "blocked_suffix_name" in rule_set:
        score += 6.0
    if "blocked_translit" in rule_set:
        score += 5.0
    if "blocked_consonant_skeleton" in rule_set:
        score += 4.0
    if "blocked_postal" in rule_set:
        score += 4.0
    if "blocked_house" in rule_set:
        score += 3.0
    if "blocked_address_name_combo" in rule_set:
        score += 3.0
    if "blocked_address_token" in rule_set:
        score += 2.0

    # 3. Lexical name similarity
    n1 = s1_rec.get("norm_name", "")
    n2 = cand_rec.get("translit_name", "") if cand_rec.get("has_indic", False) else cand_rec.get("norm_name", "")
    if n1 and n2:
        if n1 == n2:
            score += 5.0
        elif len(n1) >= 3 and len(n2) >= 3 and n1[:3] == n2[:3]:
            score += 2.0

    # 4. Postal code match
    p1 = s1_rec.get("postal_code", "")
    p2 = cand_rec.get("postal_code", "")
    if p1 and p2 and p1.lower() == p2.lower():
        score += 3.0

    # 5. House number match
    h1 = s1_rec.get("house_number", "")
    h2 = cand_rec.get("house_number", "")
    if h1 and h2 and h1.lower() == h2.lower():
        score += 2.0

    return score


