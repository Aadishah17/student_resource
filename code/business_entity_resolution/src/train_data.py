def split_s1_entities(
    s1_ids: List[str],
    train_ratio: float = 0.80,
    random_seed: int = 42
) -> Tuple[List[str], List[str]]:
    """
    Partitions Source 1 entity IDs into train and validation sets at the S1 entity level.
    Guarantees that all candidate pairs for an S1 entity belong exclusively to one split.
    """
    rng = random.Random(random_seed)
    shuffled = sorted(list(s1_ids))  # Deterministic base ordering
    rng.shuffle(shuffled)

    n_train = int(len(shuffled) * train_ratio)
    train_ids = sorted(shuffled[:n_train])
    val_ids = sorted(shuffled[n_train:])

    # Integrity verification
    assert len(set(train_ids) & set(val_ids)) == 0, "Train/Val S1 overlap detected!"
    assert len(train_ids) + len(val_ids) == len(s1_ids), "S1 entity count mismatch!"

    return train_ids, val_ids


