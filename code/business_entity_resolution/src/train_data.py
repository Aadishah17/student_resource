def sample_training_pairs_with_ratios(
    train_s1_ids: List[str],
    evidence_map: Dict[str, Dict[str, Set[str]]],
    ground_truth: Dict[str, Set[str]],
    s1_records: Dict[str, Dict[str, Any]],
    cand_records: Dict[str, Dict[str, Any]],
    ratios: List[float] = [1.0, 2.0, 4.0],
    selected_ratio: float = 4.0,
    random_seed: int = 42
) -> Tuple[List[Tuple[str, str, Set[str], int]], Dict[str, Any]]:
    """
    Constructs labeled training pairs across tested negative-to-positive ratios.
    Guarantees:
    - 100% of blocking-recalled positive candidate pairs are preserved.
    - Negatives are sampled using hard-negative prioritization + stochastic diversity.
    - Entity balancing caps per-S1 negatives to prevent outlier entities from dominating.
    """
    rng = random.Random(random_seed)

    # 1. Inspect per-S1 candidate and ground-truth distributions
    pos_counts_per_s1: List[int] = []
    cands_per_s1: List[int] = []
    negs_per_s1: List[int] = []

    s1_positives: Dict[str, List[Tuple[str, Set[str]]]] = defaultdict(list)
    s1_negatives_scored: Dict[str, List[Tuple[str, Set[str], float]]] = defaultdict(list)

    total_avail_pos = 0
    total_avail_neg = 0

    for s1_id in train_s1_ids:
        gt_matches = ground_truth.get(s1_id, set())
        cand_dict = evidence_map.get(s1_id, {})
        cands_per_s1.append(len(cand_dict))

        p_count = 0
        n_count = 0
        for cand_id, rule_set in cand_dict.items():
            if cand_id in gt_matches:
                s1_positives[s1_id].append((cand_id, rule_set))
                p_count += 1
                total_avail_pos += 1
            else:
                s1_rec = s1_records[s1_id]
                cand_rec = cand_records[cand_id]
                h_score = compute_negative_hardness(s1_rec, cand_rec, rule_set)
                s1_negatives_scored[s1_id].append((cand_id, rule_set, h_score))
                n_count += 1
                total_avail_neg += 1

        pos_counts_per_s1.append(p_count)
        negs_per_s1.append(n_count)

    # Ratio comparisons
    ratio_stats: Dict[str, Any] = {}
    for r in ratios:
        r_neg_count = 0
        for s1_id in train_s1_ids:
            p_len = len(s1_positives[s1_id])
            n_len = len(s1_negatives_scored[s1_id])
            target_n = max(2, int(p_len * r)) if p_len > 0 else min(n_len, int(r))
            r_neg_count += min(n_len, target_n)

        ratio_stats[f"ratio_{r:.1f}"] = {
            "positives": total_avail_pos,
            "negatives": r_neg_count,
            "total_pairs": total_avail_pos + r_neg_count,
            "neg_pos_ratio": r_neg_count / total_avail_pos if total_avail_pos > 0 else 0.0,
            "positive_pct": (total_avail_pos / (total_avail_pos + r_neg_count) * 100) if (total_avail_pos + r_neg_count) > 0 else 0.0
        }

    # All negatives baseline
    ratio_stats["unconstrained_all"] = {
        "positives": total_avail_pos,
        "negatives": total_avail_neg,
        "total_pairs": total_avail_pos + total_avail_neg,
        "neg_pos_ratio": total_avail_neg / total_avail_pos if total_avail_pos > 0 else 0.0,
        "positive_pct": (total_avail_pos / (total_avail_pos + total_avail_neg) * 100) if (total_avail_pos + total_avail_neg) > 0 else 0.0
    }

    # 2. Build final training set under selected_ratio (4.0:1) with entity balancing
    selected_training_pairs: List[Tuple[str, str, Set[str], int]] = []
    hard_neg_count = 0
    sampled_negs_per_s1: List[int] = []

    for s1_id in train_s1_ids:
        # A. Include ALL positive candidate pairs
        for cand_id, rule_set in s1_positives[s1_id]:
            selected_training_pairs.append((s1_id, cand_id, rule_set, 1))

        # B. Sample balanced hard negatives
        neg_candidates = s1_negatives_scored[s1_id]
        if not neg_candidates:
            sampled_negs_per_s1.append(0)
            continue

        p_len = len(s1_positives[s1_id])
        # Entity-balanced budget: 4x positives, min 2, max 25 per S1 to cap dominant entities
        if p_len > 0:
            target_n = min(len(neg_candidates), max(2, min(25, int(p_len * selected_ratio))))
        else:
            # Singleton S1 entity (no true match in candidate set)
            target_n = min(len(neg_candidates), 3)

        # Sort negatives by hardness descending
        neg_candidates.sort(key=lambda x: x[2], reverse=True)

        # 80% hardest negatives + 20% randomized negatives for regularization
        n_hard = int(target_n * 0.8)
        n_rand = target_n - n_hard

        chosen_negs: List[Tuple[str, Set[str]]] = []
        for cand_id, rule_set, _ in neg_candidates[:n_hard]:
            chosen_negs.append((cand_id, rule_set))
            hard_neg_count += 1

        remaining_negs = neg_candidates[n_hard:]
        if remaining_negs and n_rand > 0:
            rand_sample = rng.sample(remaining_negs, min(n_rand, len(remaining_negs)))
            for cand_id, rule_set, _ in rand_sample:
                chosen_negs.append((cand_id, rule_set))

        for cand_id, rule_set in chosen_negs:
            selected_training_pairs.append((s1_id, cand_id, rule_set, 0))

        sampled_negs_per_s1.append(len(chosen_negs))

    metadata = {
        "total_avail_pos": total_avail_pos,
        "total_avail_neg": total_avail_neg,
        "ratio_comparisons": ratio_stats,
        "selected_ratio": selected_ratio,
        "final_positives": total_avail_pos,
        "final_negatives": sum(sampled_negs_per_s1),
        "hard_negatives": hard_neg_count,
        "pos_per_s1_stats": {
            "mean": float(np.mean(pos_counts_per_s1)),
            "median": float(np.median(pos_counts_per_s1)),
            "p95": float(np.percentile(pos_counts_per_s1, 95)),
            "max": int(np.max(pos_counts_per_s1)),
            "zero_pos_s1_count": int(sum(1 for c in pos_counts_per_s1 if c == 0))
        },
        "neg_per_s1_stats": {
            "mean": float(np.mean(negs_per_s1)),
            "median": float(np.median(negs_per_s1)),
            "p95": float(np.percentile(negs_per_s1, 95)),
            "max": int(np.max(negs_per_s1)),
        },
        "sampled_neg_per_s1_stats": {
            "mean": float(np.mean(sampled_negs_per_s1)),
            "median": float(np.median(sampled_negs_per_s1)),
            "p95": float(np.percentile(sampled_negs_per_s1, 95)),
            "max": int(np.max(sampled_negs_per_s1)),
        },
        "cands_per_s1_stats": {
            "mean": float(np.mean(cands_per_s1)),
            "median": float(np.median(cands_per_s1)),
            "p95": float(np.percentile(cands_per_s1, 95)),
            "max": int(np.max(cands_per_s1)),
        }
    }

    return selected_training_pairs, metadata


